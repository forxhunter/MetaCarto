"""Regenerate `src/layout/organisms.py` from the BiGG model list.

The map picker lists models by their BiGG identifier -- iJO1366, iML1515,
iYS1720 -- which is unsearchable unless you already know which organism you
want. BiGG's `/api/v2/models` carries an `organism` field for every model, so
the identifier can be shown and searched next to the species.

The result is written as a Python module rather than JSON because `data/` and
`*.json` are both gitignored, and this table has to ship with the code: the
index is built on machines that have the repository and may not have the
network.

    python scripts/fetch_bigg_organisms.py
    python scripts/fetch_bigg_organisms.py --check   # non-zero if out of date
"""

