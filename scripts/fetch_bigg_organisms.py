def binomial_of(organism):
    """Genus and species, with the strain suffix removed."""
    if not organism:
        return ""
    parts = organism.split()
    if len(parts) >= 2 and parts[1][:1].islower():
        return " ".join(parts[:2])
    return parts[0] if parts else ""


def render_module(models):
    lines = [HEADER, "ORGANISM = {\n"]
    for m in sorted(models, key=lambda m: m["bigg_id"]):
        lines.append("    %r: %r,\n" % (m["bigg_id"], m.get("organism") or ""))
    lines.append("}\n\nCOMMON = {\n")
