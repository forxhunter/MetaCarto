def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", default=TARGET)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the module is out of date")
    args = parser.parse_args(argv)

    with urllib.request.urlopen(API, timeout=60) as response:
        models = json.load(response)["results"]
    print("BiGG returned %d models" % len(models))

    missing = sorted({binomial_of(m.get("organism")) for m in models}
                     - set(COMMON_NAMES) - {""})
    if missing:
        print("no common name for: %s" % ", ".join(missing))

    text = render_module(models)
    old = None
    if os.path.exists(args.target):
        with open(args.target, encoding="utf-8") as handle:
            old = handle.read()
    if args.check:
        if old != text:
            print("%s is out of date" % args.target)
            return 1
        print("%s matches BiGG" % args.target)
        return 0

    with open(args.target, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("wrote %s (%d organisms, %d common names)"
          % (args.target, len(models), len(COMMON_NAMES)))
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
